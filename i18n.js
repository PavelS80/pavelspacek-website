/* ============================================================
   Apply + switcher (event delegation covers cloned switchers)
   ============================================================ */
function applyLang(lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const val = dict[el.dataset.i18n];
    if (val !== undefined) el.innerHTML = val;
  });
  document.querySelectorAll('[data-lang-btn]').forEach(btn => {
    btn.classList.toggle('lang-active', btn.dataset.langBtn === lang);
  });
  try { localStorage.setItem('ps-lang', lang); } catch (e) { /* private mode */ }
}

document.addEventListener('click', e => {
  const btn = e.target.closest('[data-lang-btn]');
  if (btn) applyLang(btn.dataset.langBtn);
});

document.addEventListener('DOMContentLoaded', () => {
  let saved = 'en';
  try { saved = localStorage.getItem('ps-lang') || 'en'; } catch (e) { /* ignore */ }
  if (saved !== 'en') applyLang(saved);
});
